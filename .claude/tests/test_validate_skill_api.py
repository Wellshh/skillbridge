class OverloadTests(ValidatorTestBase):
    def test_overloaded_symbol_accepts_any_documented_form(self):
        index = AXL_INDEX + (
            "| `axlDbidName` | `axlDbidName( o_dbid t_fmt ) => t_name/nil` "
            "| `algroskill/25dbmisc.md` | 11 |\n"
        )
        (self.root / "api_index.part01.md").write_text(index, encoding="utf-8")
        specs = self.validator.load_corpus(self.root)
        self.assertEqual(len(specs["axldbidname"].arities), 2)
        self.assertEqual(specs["axldbidname"].arity_summary(), "1 or 2")

        path = Path(self.temp_dir.name) / "demo.il"
        for source in ("axlDbidName( o_net )\n", 'axlDbidName( o_net "fmt" )\n'):
            path.write_text(source, encoding="utf-8")
            self.assertEqual(
                self.validator.validate_file(path, self.root, specs, "demo.il"),
                [],
                source,
            )

        # three arguments matches neither overload
        path.write_text('axlDbidName( o_net "fmt" "extra" )\n', encoding="utf-8")
        findings = self.validator.validate_file(path, self.root, specs, "demo.il")
        self.assertEqual([f.check for f in findings], ["arity"])

    def test_variadic_overload_disables_arity_checking(self):
        index = AXL_INDEX + (
            "| `axlDbidName` | `axlDbidName( o_dbid g_args... ) => t_name/nil` "
            "| `algroskill/25dbmisc.md` | 12 |\n"
        )
        (self.root / "api_index.part01.md").write_text(index, encoding="utf-8")
        specs = self.validator.load_corpus(self.root)
        self.assertFalse(specs["axldbidname"].countable)

        path = Path(self.temp_dir.name) / "demo.il"
        path.write_text("axlDbidName( o_net 1 2 3 4 )\n", encoding="utf-8")
        self.assertEqual(
            self.validator.validate_file(path, self.root, specs, "demo.il"), []
        )


class HallucinationScenarioTests(ValidatorTestBase):
    """End-to-end: the bug class this validator exists to catch.

    ``skill_lint.py`` is purely lexical and passes all of this with exit 0, so
    these are the findings that previously reached a Windows Allegro session
    before anyone noticed the APIs did not exist.
    """

    SAMPLE = """\
procedure( myDemoScript( t_netName )
  let( ( o_net l_shapes )
    o_net = axlGetNetByName( t_netName )
    l_shapes = axlDBGetDesign()->shapes
    axlSelectByName( "NET" t_netName "ETCH" )
    axlNetRenameTo( o_net "newname" )
    t
  )
)
"""

    def test_every_invented_api_is_reported(self):
        findings = self.findings(self.SAMPLE)
        unknown = sorted(
            f.message.split("'")[1] for f in findings if f.check == "unknown-api"
        )
        self.assertEqual(unknown, ["axlGetNetByName", "axlNetRenameTo"])

    def test_real_apis_in_the_same_file_are_not_reported(self):
        findings = self.findings(self.SAMPLE)
        reported = {f.message.split("'")[1] for f in findings if f.check == "unknown-api"}
        self.assertNotIn("axlDBGetDesign", reported)
        self.assertNotIn("axlSelectByName", reported)

    def test_locally_defined_procedure_is_not_reported(self):
        findings = self.findings(self.SAMPLE)
        reported = {f.message.split("'")[1] for f in findings if f.check == "unknown-api"}
        self.assertNotIn("myDemoScript", reported)

    def test_exit_code_is_nonzero_when_errors_exist(self):
        path = Path(self.temp_dir.name) / "demo.il"
        path.write_text(self.SAMPLE, encoding="utf-8")
        code = self.validator.main([str(path), "--root", str(self.root)])
        self.assertEqual(code, 1)

    def test_exit_code_is_zero_for_clean_code(self):
        path = Path(self.temp_dir.name) / "clean.il"
        path.write_text('axlDbidName( axlDBCreateNet( "N1" ) )\n', encoding="utf-8")
        code = self.validator.main([str(path), "--root", str(self.root)])
        self.assertEqual(code, 0)

    def test_suggestion_points_at_the_right_real_api(self):
        findings = self.findings("axlNetRenameTo( o_net \"new\" )\n")
        self.assertIn("axlRenameNet", findings[0].message)


class BaselineTests(ValidatorTestBase):
    def test_measure_reports_the_expected_shape(self):
        examples = self.root / "examples"
        examples.mkdir()
        (examples / "good.il").write_text(
            'axlDbidName( axlDBCreateNet( "N1" ) )\n', encoding="utf-8"
        )
        (examples / "bad.il").write_text("axlInventedApi( 1 )\n", encoding="utf-8")
        measured = self.validator._measure(self.root)
        self.assertEqual(measured["example_files"], 2)
        self.assertEqual(measured["files_with_errors"], 1)
        self.assertEqual(measured["total_errors"], 1)
        self.assertEqual(measured["by_check"], {"unknown-api": 1})

    def test_check_fails_without_a_baseline(self):
        examples = self.root / "examples"
        examples.mkdir()
        (examples / "good.il").write_text("println( 1 )\n", encoding="utf-8")
        self.validator.BASELINE_PATH = Path(self.temp_dir.name) / "absent.json"
        self.assertEqual(self.validator.self_test(self.root, check=True), 1)

    def test_check_passes_when_baseline_holds(self):
        examples = self.root / "examples"
        examples.mkdir()
        (examples / "good.il").write_text("println( 1 )\n", encoding="utf-8")
        self.validator.BASELINE_PATH = Path(self.temp_dir.name) / "baseline.json"
        self.assertEqual(self.validator.self_test(self.root, write_baseline=True), 0)
        self.assertEqual(self.validator.self_test(self.root, check=True), 0)

    def test_check_fails_when_false_positives_rise(self):
        examples = self.root / "examples"
        examples.mkdir()
        (examples / "good.il").write_text("println( 1 )\n", encoding="utf-8")
        self.validator.BASELINE_PATH = Path(self.temp_dir.name) / "baseline.json"
        self.validator.self_test(self.root, write_baseline=True)
        # a new correct-by-vendor file the corpus cannot resolve regresses the gate
        (examples / "newer.il").write_text("axlBrandNewApi( 1 )\n", encoding="utf-8")
        self.assertEqual(self.validator.self_test(self.root, check=True), 1)


