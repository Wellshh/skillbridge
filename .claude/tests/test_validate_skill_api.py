class ValidatorTestBase(unittest.TestCase):
    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.root = Path(self.temp_dir.name) / "skill-references"
        self.root.mkdir()
        (self.root / "api_index.part01.md").write_text(AXL_INDEX, encoding="utf-8")
        (self.root / "sklang_api_index.part01.md").write_text(
            SKLANG_INDEX, encoding="utf-8"
        )
        self.validator = load_validator()
        self.specs = self.validator.load_corpus(self.root)

    def tearDown(self):
        self.temp_dir.cleanup()

    def findings(self, source, name="demo.il"):
        path = Path(self.temp_dir.name) / name
        path.write_text(source, encoding="utf-8")
        return self.validator.validate_file(path, self.root, self.specs, name)

    def checks(self, source, name="demo.il"):
        return [f.check for f in self.findings(source, name)]


class CorpusLoadingTests(ValidatorTestBase):
    def test_loads_both_indexes(self):
        self.assertIn("axldbidname", self.specs)
        self.assertIn("println", self.specs)

    def test_parses_required_and_optional_arity(self):
        spec = self.specs["axlselectbyname"]
        self.assertEqual(spec.arities[0].required, 2)
        self.assertEqual(spec.arities[0].optional, 1)
        self.assertTrue(spec.accepts(2))
        self.assertTrue(spec.accepts(3))
        self.assertFalse(spec.accepts(1))

    def test_bracketed_keyword_group_counts_as_one_optional(self):
        arity = self.validator._parse_arity(
            "loadPort( p_port [?langMode g_langMode] [?password g_password] ) => t",
        )
        self.assertEqual(arity.required, 1)
        self.assertEqual(arity.optional, 2)
        self.assertEqual(arity.keywords, ("langMode", "password"))
        # keyword args make positional counting ambiguous
        self.assertFalse(arity.countable)

    def test_variadic_signature_is_not_countable(self):
        spec = self.specs["axlshell"]
        self.assertFalse(spec.countable)
        self.assertTrue(spec.arities[0].variadic)

    def test_keyword_signature_collects_keyword_names(self):
        spec = self.specs["axlcmdregister"]
        self.assertEqual(spec.keywords, ("cmdType", "doneCmd"))
        self.assertFalse(spec.countable)

    def test_choice_group_counts_as_one_positional_slot(self):
        # t_name/lt_name is one parameter accepting either form
        self.assertEqual(self.specs["axlselectbyname"].arities[0].required, 2)

    def test_arity_summary_reads_well(self):
        self.assertEqual(self.specs["axlselectbyname"].arity_summary(), "2-3")
        self.assertEqual(self.specs["axldbidname"].arity_summary(), "1")


class UnknownApiTests(ValidatorTestBase):
    def test_invented_axl_name_is_an_error(self):
        findings = self.findings("axlGetNetByName( 'net )\n")
        self.assertEqual([f.check for f in findings], ["unknown-api"])
        self.assertEqual(findings[0].severity, "error")

    def test_error_message_suggests_real_candidates(self):
        findings = self.findings("axlRenameNetTo( o_net \"new\" )\n")
        self.assertTrue(findings)
        self.assertIn("did you mean", findings[0].message)
        self.assertIn("axlRenameNet", findings[0].message)

    def test_known_axl_name_passes(self):
        self.assertEqual(self.findings("axlDbidName( o_net )\n"), [])

    def test_verified_platform_callable_without_corpus_signature_passes(self):
        findings = self.validator.validate_text(
            "axlXSectionAssign( first second )\n",
            self.specs,
            "demo.il",
            {"axlxsectionassign"},
        )
        self.assertEqual(findings, [])

    def test_unverified_platform_callable_is_still_an_error(self):
        findings = self.validator.validate_text(
            "axlXSectionAssign( first second )\n",
            self.specs,
            "demo.il",
            set(),
        )
        self.assertEqual([finding.check for finding in findings], ["unknown-api"])

    def test_non_axl_unknown_prefix_is_out_of_scope(self):
        # dbc*/tsel*/ash* namespaces are not covered by this corpus
        self.assertEqual(self.findings("dbcFooBar( 1 2 )\ntselInit( )\n"), [])

    def test_general_skill_builtin_not_flagged_as_unknown(self):
        # the language reference does not index every SKILL builtin
        self.assertEqual(self.findings("sortcar( l_list 'alpha )\n"), [])

    def test_name_inside_comment_is_not_a_call_site(self):
        self.assertEqual(self.findings("; axlGetNetByName( x )\nprintln( 1 )\n"), [])

    def test_name_inside_string_is_not_a_call_site(self):
        self.assertEqual(self.findings('println( "axlGetNetByName( x )" )\n'), [])


class ScopeAnalysisTests(ValidatorTestBase):
    def test_locally_defined_procedure_is_not_flagged(self):
        source = (
            "procedure( axlMyHelper( x )\n"
            "  x + 1\n"
            ")\n"
            "axlMyHelper( 2 )\n"
        )
        self.assertEqual(self.findings(source), [])

    def test_let_bound_variable_is_not_flagged(self):
        source = "let( ( axlTempVar )\n  axlTempVar( 1 )\n)\n"
        self.assertEqual(self.findings(source), [])

    def test_lambda_parameter_is_not_flagged(self):
        source = "mapcar( lambda( ( axlItem ) axlItem( ) ) l_list )\n"
        self.assertEqual(self.findings(source), [])

    def test_assignment_target_is_not_flagged(self):
        source = "axlMyGlobal = 5\naxlMyGlobal( 1 )\n"
        self.assertEqual(self.findings(source), [])

    def test_foreach_variable_is_not_flagged(self):
        source = "foreach( axlEachItem l_list\n  axlEachItem( )\n)\n"
        self.assertEqual(self.findings(source), [])

    def test_defun_like_form_binds_a_name(self):
        # `define` takes the bound name as its first argument
        source = "define( axlMyFn lambda( ( x ) x ) )\naxlMyFn( 1 )\n"
        self.assertEqual(self.findings(source), [])

    def test_registering_form_does_not_bind_the_name(self):
        # defUserInitProc registers an already-existing procedure; it does not
        # define axlInitFn, so calling an undeclared one is still flagged
        source = 'defUserInitProc( "ctx" axlInitFn )\naxlInitFn( )\n'
        findings = self.findings(source)
        self.assertEqual([f.check for f in findings], ["unknown-api"])
        self.assertEqual(findings[0].line, 2)

    def test_leading_string_does_not_block_head_detection(self):
        # the bound name is still found when a literal precedes it
        source = 'defclass( "card" axlCardClass )\naxlCardClass( )\n'
        self.assertEqual(self.findings(source), [])

    def test_lisp_prefix_defun_binds_the_name(self):
        # official examples use ``(defun axlfoo_t0 () ...)`` for test helpers
        source = "(defun axlenter_t0 ()\n  (axlDbidName x)\n)\n(axlenter_t0)\n"
        self.assertEqual(self.findings(source), [])

    def test_lisp_prefix_let_binds_variables(self):
        source = "(let ( axlTempA axlTempB )\n  axlTempA = 1\n  axlTempB( 2 )\n)\n"
        self.assertEqual(self.findings(source), [])


class PrefixCallSyntaxTests(ValidatorTestBase):
    def test_prefix_call_does_not_leak_inner_arguments(self):
        # ``(null (car x))`` must count one argument for null, not two
        lexed = self.validator.strip_comments_and_strings(
            "((null (axlDbidName orderedList))\n"
        )
        sites = {s.name: s.arguments for s in self.validator.find_call_sites(lexed)}
        self.assertEqual(sites["null"], ["(axlDbidName orderedList)"])
        self.assertEqual(sites["axlDbidName"], ["orderedList"])

    def test_prefix_call_is_detected(self):
        findings = self.findings("(axlGetNetByName x)\n")
        self.assertEqual([f.check for f in findings], ["unknown-api"])

    def test_prefix_call_arity_is_checked(self):
        findings = self.findings('(axlRenameNet "old")\n')
        self.assertEqual([f.check for f in findings], ["arity"])

    def test_quoted_list_is_not_a_call_site(self):
        # '( axlFoo bar ) is data, not a call
        self.assertEqual(self.findings("l = '( axlInventedOne 1 2 )\n"), [])


