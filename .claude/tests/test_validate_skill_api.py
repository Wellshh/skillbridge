class LexingTests(ValidatorTestBase):
    def test_strip_preserves_line_numbers(self):
        lexed = self.validator.strip_comments_and_strings(
            "a\n; comment\nb\n\"str\ng\"\nc\n"
        )
        # the newline inside the unterminated string is preserved too, so the
        # author's line numbering survives lexing
        self.assertEqual(lexed.count("\n"), 6)

    def test_escaped_quote_does_not_end_string(self):
        lexed = self.validator.strip_comments_and_strings(r'"a\"b( c" ; x')
        self.assertNotIn("(", lexed.split(";")[0])

    def test_semicolon_inside_string_is_not_a_comment(self):
        # string contents are blanked, but the literal must not swallow the
        # rest of the line the way a real comment would
        lexed = self.validator.strip_comments_and_strings('println( "a;b" )')
        self.assertTrue(lexed.rstrip().endswith(")"))

    def test_string_literal_stays_one_argument_token(self):
        # a space-filled literal would be re-split into several tokens and
        # corrupt the arity count
        lexed = self.validator.strip_comments_and_strings('f( "a b c" )')
        self.assertEqual(self.validator._split_arguments(lexed[2:-2]), ['"\x00\x00\x00\x00\x00"'])

    def test_call_site_column_is_one_based(self):
        findings = self.findings("  axlGetNetByName( x )\n")
        self.assertEqual(findings[0].column, 3)

    def test_column_is_correct_after_a_preceding_string(self):
        # offset-preserving blanking keeps the reported column the author's
        findings = self.findings('println( "0123456789" ) axlGetNetByName( x )\n')
        self.assertEqual(findings[0].column, 25)

    def test_nested_calls_are_both_found(self):
        checks = self.checks("axlDbidName( axlInventedOne( x ) )\n")
        self.assertIn("unknown-api", checks)


