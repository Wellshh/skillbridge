import importlib.util
import json
import sys
import tempfile
import unittest
from pathlib import Path

SCRIPTS_DIR = Path(__file__).parents[1] / "scripts"


def load_module(filename, module_name):
    if str(SCRIPTS_DIR) not in sys.path:
        sys.path.insert(0, str(SCRIPTS_DIR))
    spec = importlib.util.spec_from_file_location(module_name, SCRIPTS_DIR / filename)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {filename}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


INDEX = """\
<!-- Generated by scripts/build_reference_indexes.py; do not edit manually. -->

# axl* API Index (part 1 of 1)

| Symbol | Documented declaration | Source | Line |
|---|---|---|---:|
| `axlDbidName` | `axlDbidName( o_dbid ) => t_name/nil` | `algroskill/dbidname.md` | 17 |
| `axlRenameNet` | `axlRenameNet( t_old_name t_new_name ) => t/nil` | `algroskill/renamenet.md` | 3 |
"""

CLEAN_SAMPLE = """\
procedure( renameNet(t_old t_new)
    axlRenameNet(t_old t_new)
)
"""

HALLUCINATED_SAMPLE = """\
procedure( renameNet(t_old t_new)
    axlNetRenameTo(t_old t_new)
)
"""


class EvalGenerationTestBase(unittest.TestCase):
    def setUp(self):
        self.eval_generation = load_module("eval_generation.py", "eval_generation")
        self.temp_dir = tempfile.TemporaryDirectory()
        base = Path(self.temp_dir.name)
        self.root = base / "skill-references"
        self.root.mkdir(parents=True)
        (self.root / "api_index.part01.md").write_text(INDEX, encoding="utf-8")
        self.samples = base / "samples"
        self.samples.mkdir()

    def tearDown(self):
        self.temp_dir.cleanup()

    def write_sample(self, name, text):
        (self.samples / name).write_text(text, encoding="utf-8")

    def measure(self):
        return self.eval_generation.measure(self.samples, self.root)


class MeasureTests(EvalGenerationTestBase):
    def test_clean_sample_has_zero_hallucinations(self):
        self.write_sample("rename-net.il", CLEAN_SAMPLE)
        metrics = self.measure()
        self.assertEqual(metrics["files"], 1)
        self.assertEqual(metrics["unknown_api_errors"], 0)
        self.assertEqual(metrics["hallucination_rate"], 0.0)
        self.assertEqual(metrics["files_with_errors"], 0)

    def test_invented_api_raises_hallucination_rate(self):
        self.write_sample("rename-net.il", CLEAN_SAMPLE)
        self.write_sample("rename-net-2.il", HALLUCINATED_SAMPLE)
        metrics = self.measure()
        self.assertEqual(metrics["files"], 2)
        self.assertEqual(metrics["unknown_api_errors"], 1)
        self.assertEqual(metrics["hallucination_rate"], 0.5)
        self.assertEqual(metrics["files_with_errors"], 1)

    def test_per_file_report_names_the_offender(self):
        self.write_sample("bad.il", HALLUCINATED_SAMPLE)
        metrics = self.measure()
        self.assertIn("bad.il", metrics["per_file"])
        self.assertIn("unknown-api", metrics["per_file"]["bad.il"][0])
        self.assertIn("axlNetRenameTo", metrics["per_file"]["bad.il"][0])

    def test_empty_samples_directory_is_an_error(self):
        with self.assertRaises(FileNotFoundError):
            self.measure()

    def test_ils_files_are_included(self):
        self.write_sample("script.ils", CLEAN_SAMPLE)
        self.assertEqual(self.measure()["files"], 1)


class ExpectedApiTests(EvalGenerationTestBase):
    def write_tasks(self, expected):
        (self.samples / "eval_tasks.json").write_text(
            json.dumps({"schema_version": 1, "tasks": [
                {"id": "rename-net", "prompt": "...", "expected_apis": expected}
            ]}),
            encoding="utf-8",
        )

    def test_expected_api_present_leaves_no_gap(self):
        self.write_tasks(["axlRenameNet"])
        self.write_sample("rename-net.il", CLEAN_SAMPLE)
        self.assertEqual(self.measure()["expected_api_missing"], {})

    def test_expected_api_avoided_is_reported_not_gated(self):
        self.write_tasks(["axlRenameNet", "axlDbidName"])
        self.write_sample("rename-net.il", CLEAN_SAMPLE)
        metrics = self.measure()
        self.assertEqual(
            metrics["expected_api_missing"], {"rename-net": ["axlDbidName"]}
        )
        # avoiding an expected API is a report signal, not an error
        self.assertEqual(metrics["files_with_errors"], 0)

    def test_task_without_matching_sample_is_ignored(self):
        self.write_tasks(["axlRenameNet"])
        self.write_sample("other-task.il", CLEAN_SAMPLE)
        self.assertEqual(self.measure()["expected_api_missing"], {})


class BaselineTests(EvalGenerationTestBase):
    def setUp(self):
        super().setUp()
        # point the baseline file at the temp dir so tests do not touch the
        # real eval_generation_baseline.json
        self.baseline_path = Path(self.temp_dir.name) / "baseline.json"
        self.eval_generation.BASELINE_PATH = self.baseline_path

    def run_main(self, *extra):
        return self.eval_generation.main(
            ["--samples", str(self.samples), "--root", str(self.root), *extra]
        )

    def test_check_without_baseline_fails(self):
        self.write_sample("rename-net.il", CLEAN_SAMPLE)
        self.assertEqual(self.run_main("--check"), 1)

    def test_baseline_roundtrip_holds_on_same_samples(self):
        self.write_sample("rename-net.il", CLEAN_SAMPLE)
        self.assertEqual(self.run_main("--write-baseline"), 0)
        self.assertEqual(self.run_main("--check"), 0)

    def test_hallucination_regression_fails_check(self):
        self.write_sample("rename-net.il", CLEAN_SAMPLE)
        self.run_main("--write-baseline")
        self.write_sample("rename-net-2.il", HALLUCINATED_SAMPLE)
        self.assertEqual(self.run_main("--check"), 1)

    def test_shrinking_the_sample_set_fails_check(self):
        self.write_sample("rename-net.il", CLEAN_SAMPLE)
        self.write_sample("rename-net-2.il", CLEAN_SAMPLE)
        self.run_main("--write-baseline")
        (self.samples / "rename-net-2.il").unlink()
        self.assertEqual(self.run_main("--check"), 1)

    def test_improvement_passes_check(self):
        self.write_sample("bad.il", HALLUCINATED_SAMPLE)
        self.run_main("--write-baseline")
        self.write_sample("bad.il", CLEAN_SAMPLE)
        self.assertEqual(self.run_main("--check"), 0)


if __name__ == "__main__":
    unittest.main()
